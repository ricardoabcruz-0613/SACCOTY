CREATE TABLE users (
 id SERIAL PRIMARY KEY, name TEXT NOT NULL, email TEXT NOT NULL UNIQUE,
 password TEXT NOT NULL, role TEXT NOT NULL CHECK(role IN ('Colaborador','Gestor','Administrador')),
 team TEXT NOT NULL DEFAULT '', active BOOLEAN NOT NULL DEFAULT FALSE,
 balance BIGINT NOT NULL DEFAULT 0 CHECK(balance >= 0 AND balance <= 9000000000000)
);
CREATE TABLE products(id SERIAL PRIMARY KEY, data JSONB NOT NULL);
CREATE TABLE orders(id SERIAL PRIMARY KEY, uid INTEGER NOT NULL REFERENCES users(id), request TEXT NOT NULL UNIQUE, data JSONB NOT NULL);
CREATE TABLE ledger(id SERIAL PRIMARY KEY, uid INTEGER NOT NULL REFERENCES users(id), amount BIGINT NOT NULL, reason TEXT NOT NULL, date TEXT NOT NULL, by TEXT NOT NULL, request TEXT UNIQUE, actor INTEGER REFERENCES users(id));
CREATE TABLE sessions(token TEXT PRIMARY KEY, uid INTEGER NOT NULL REFERENCES users(id), expires BIGINT NOT NULL, csrf TEXT NOT NULL);
CREATE INDEX sessions_expiry ON sessions(expires);
CREATE TABLE attempts(key TEXT PRIMARY KEY, count INTEGER NOT NULL, expires BIGINT NOT NULL);
CREATE TABLE audit(id SERIAL PRIMARY KEY, date TEXT NOT NULL, actor INTEGER REFERENCES users(id), action TEXT NOT NULL, detail JSONB NOT NULL);
CREATE TABLE app_lock(id INTEGER PRIMARY KEY CHECK(id=1));
